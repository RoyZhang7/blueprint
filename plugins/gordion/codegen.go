package gordion

import (
	"fmt"
	"path/filepath"
	"sort"

	"github.com/blueprint-uservices/blueprint/plugins/golang"
	"github.com/blueprint-uservices/blueprint/plugins/golang/gocode"
	"github.com/blueprint-uservices/blueprint/plugins/golang/gogen"
	"golang.org/x/exp/slog"
)

const runtimePackage = "github.com/blueprint-uservices/blueprint/runtime/plugins/gordion"

type methodArg struct {
	Index int
	Func  gocode.Func
}

type wrapperArgs struct {
	Package golang.PackageInfo
	Service *gocode.ServiceInterface
	Name    string
	Imports *gogen.Imports
	Methods []methodArg // sorted by name; Index is the position in this list
}

// sortedMethods gives every method a stable index (sorted by name). The
// recorder is created with the names in the same order, so the index passed
// to Begin matches the name printed in the output.
func sortedMethods(iface *gocode.ServiceInterface) []methodArg {
	names := make([]string, 0, len(iface.Methods))
	for n := range iface.Methods {
		names = append(names, n)
	}
	sort.Strings(names)
	out := make([]methodArg, len(names))
	for i, n := range names {
		out[i] = methodArg{Index: i, Func: iface.Methods[n]}
	}
	return out
}

func generateServerWrapper(builder golang.ModuleBuilder, wrapped *gocode.ServiceInterface, outputPackage string) error {
	pkg, err := builder.CreatePackage(outputPackage)
	if err != nil {
		return err
	}
	args := wrapperArgs{
		Package: pkg,
		Service: wrapped,
		Name:    wrapped.BaseName + "_GordionServer",
		Imports: gogen.NewImports(pkg.Name),
		Methods: sortedMethods(wrapped),
	}
	args.Imports.AddPackages("context", runtimePackage)
	slog.Info(fmt.Sprintf("Generating %v/%v", pkg.PackageName, args.Name))
	outputFile := filepath.Join(pkg.Path, args.Name+".go")
	return gogen.ExecuteTemplateToFile("GordionServer", serverTemplate, args, outputFile)
}

